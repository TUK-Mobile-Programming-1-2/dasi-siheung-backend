-- 활동 전후 사진. 확정 예약의 신청자 · 공간 제공자가 이용 전 상태와 원상 복구 상태를 남긴다. (비공개 버킷)
CREATE TABLE activity_photo
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL REFERENCES space_application (id) ON DELETE CASCADE,
    uploader_id    BIGINT       NOT NULL REFERENCES member (id),
    uploader_side  VARCHAR(20)  NOT NULL,
    phase          VARCHAR(10)  NOT NULL,
    storage_path   VARCHAR(300) NOT NULL,
    original_name  VARCHAR(255),
    content_type   VARCHAR(100) NOT NULL,
    file_size      BIGINT       NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    CONSTRAINT ck_activity_photo_side CHECK (uploader_side IN ('APPLICANT', 'PROVIDER')),
    CONSTRAINT ck_activity_photo_phase CHECK (phase IN ('BEFORE', 'AFTER'))
);

CREATE INDEX idx_activity_photo_application ON activity_photo (application_id, phase, id);

COMMENT ON TABLE activity_photo IS '활동 전후 사진 (분쟁 시 원상 복구 확인용)';
COMMENT ON COLUMN activity_photo.phase IS 'BEFORE 이용 전 | AFTER 이용 후';
