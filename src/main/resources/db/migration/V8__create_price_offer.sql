-- 가격 제안 · 역제안 이력. 신청의 현재 협의 상태는 space_application 에 있다.
CREATE TABLE price_offer
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT       NOT NULL REFERENCES space_application (id) ON DELETE CASCADE,
    proposer_id    BIGINT       NOT NULL REFERENCES member (id),
    proposer_side  VARCHAR(20)  NOT NULL,
    amount         INTEGER      NOT NULL,
    message        VARCHAR(300),
    accepted_at    TIMESTAMP,
    created_at     TIMESTAMP    NOT NULL,
    CONSTRAINT ck_price_offer_side CHECK (proposer_side IN ('APPLICANT', 'PROVIDER')),
    CONSTRAINT ck_price_offer_amount CHECK (amount > 0)
);

CREATE INDEX idx_price_offer_application ON price_offer (application_id, id);

COMMENT ON TABLE price_offer IS '가격 제안 · 역제안 이력';
COMMENT ON COLUMN price_offer.proposer_side IS 'APPLICANT 신청자 제안 | PROVIDER 공간 제공자 역제안';
COMMENT ON COLUMN price_offer.accepted_at IS '상대가 수락한 시각 (수락된 제안만)';
