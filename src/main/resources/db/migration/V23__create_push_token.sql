-- 푸시 알림(FCM) 기기 토큰. 회원 한 명이 여러 기기를 쓸 수 있고, 한 토큰은 한 회원에게만 속한다.
-- 같은 기기에서 다른 계정으로 로그인하면 토큰이 새 회원에게 옮겨 간다.
-- 로그아웃 · 탈퇴하면 지우고, FCM 이 더 이상 쓸 수 없다고 답한 토큰과 60일 넘게 다시 등록되지 않은 토큰도 지운다.
CREATE TABLE push_token
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id          BIGINT       NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    token              VARCHAR(512) NOT NULL,
    created_at         TIMESTAMP    NOT NULL,
    last_registered_at TIMESTAMP    NOT NULL,
    CONSTRAINT uk_push_token_token UNIQUE (token)
);

CREATE INDEX idx_push_token_member ON push_token (member_id);
CREATE INDEX idx_push_token_last_registered_at ON push_token (last_registered_at);

COMMENT ON TABLE push_token IS 'FCM 기기 토큰 (앱이 시작 · 토큰 갱신 때 등록)';
COMMENT ON COLUMN push_token.last_registered_at IS '마지막으로 등록된 시각 — 오래되면 쓰지 않는 기기로 보고 지운다';
