-- 사용자 차단. 한 사람이라도 상대를 차단했으면 두 사람은 서로 메시지를 보내거나 새 대화를 열 수 없다.
-- 이미 있는 대화방 · 메시지는 그대로 보인다 (신고 증거로도 쓰인다).
-- 탈퇴해도 회원 행은 남으므로 차단 기록도 남아 목록에서 해제할 수 있다.
CREATE TABLE member_block
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT    NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    blocked_id BIGINT    NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_member_block_blocker_blocked UNIQUE (blocker_id, blocked_id),
    CONSTRAINT ck_member_block_not_self CHECK (blocker_id <> blocked_id)
);

CREATE INDEX idx_member_block_blocker_created ON member_block (blocker_id, created_at DESC);

COMMENT ON TABLE member_block IS '사용자 차단 (blocker 가 blocked 를 차단)';
COMMENT ON COLUMN member_block.created_at IS '차단한 시각 — 차단 목록은 최근 차단 순';
