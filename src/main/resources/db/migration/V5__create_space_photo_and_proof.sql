-- 공간 사진 (공개 버킷). 주소는 저장하지 않고 버킷 안의 경로만 저장한다.
CREATE TABLE space_photo
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id     BIGINT       NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    storage_path VARCHAR(300) NOT NULL,
    sort_order   INTEGER      NOT NULL,
    created_at   TIMESTAMP    NOT NULL
);

CREATE INDEX idx_space_photo_space ON space_photo (space_id, sort_order);

-- 공간 제공 권한 증빙 (비공개 버킷). 관리자 검수에서만 임시 주소로 열람한다.
CREATE TABLE space_proof
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id      BIGINT       NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    proof_type    VARCHAR(30)  NOT NULL,
    storage_path  VARCHAR(300) NOT NULL,
    original_name VARCHAR(255),
    content_type  VARCHAR(100) NOT NULL,
    file_size     BIGINT       NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

CREATE INDEX idx_space_proof_space ON space_proof (space_id);

COMMENT ON TABLE space_photo IS '공간 현장 사진 (공개)';
COMMENT ON TABLE space_proof IS '공간 제공 권한 증빙 (비공개, 관리자 검수용)';
COMMENT ON COLUMN space_proof.proof_type IS 'REGISTRY_CERTIFICATE 등기사항증명서 / LEASE_CONTRACT 임대차계약서 / SUBLEASE_CONSENT 전대 동의서 / POWER_OF_ATTORNEY 위임장 / BUSINESS_REGISTRATION 사업자등록증 / OTHER 기타';
