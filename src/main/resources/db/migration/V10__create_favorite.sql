-- 찜. 공간별 찜 수는 목록 정렬(인기순)에 쓰므로 space 에 함께 둔다.
CREATE TABLE favorite
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  BIGINT    NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    space_id   BIGINT    NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_favorite_member_space UNIQUE (member_id, space_id)
);

CREATE INDEX idx_favorite_member ON favorite (member_id, created_at DESC);

ALTER TABLE space
    ADD COLUMN favorite_count INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_space_favorite_count CHECK (favorite_count >= 0);

COMMENT ON TABLE favorite IS '찜한 공간';
COMMENT ON COLUMN space.favorite_count IS '찜 수 — 찜 추가·해제 시 UPDATE 한 문장으로 더하고 뺀다';
