-- 공간
CREATE TABLE space
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id      BIGINT                NOT NULL REFERENCES member (id),
    title            VARCHAR(60)           NOT NULL,
    description      VARCHAR(2000)         NOT NULL,
    rules            VARCHAR(2000),
    region           VARCHAR(20)           NOT NULL REFERENCES service_region (code),
    address          VARCHAR(200)          NOT NULL,
    building_name    VARCHAR(60),
    unit_number      VARCHAR(30),
    location         geometry(Point, 4326) NOT NULL,
    area_sqm         NUMERIC(8, 2)         NOT NULL,
    building_use     VARCHAR(30)           NOT NULL,
    commercial_theme VARCHAR(30),
    daily_price      INTEGER               NOT NULL,
    status           VARCHAR(20)           NOT NULL,
    review_comment   VARCHAR(1000),
    reviewed_at      TIMESTAMP,
    version          BIGINT                NOT NULL DEFAULT 0,
    created_at       TIMESTAMP             NOT NULL,
    updated_at       TIMESTAMP             NOT NULL,
    CONSTRAINT ck_space_area CHECK (area_sqm > 0),
    CONSTRAINT ck_space_daily_price CHECK (daily_price >= 0),
    CONSTRAINT ck_space_status CHECK (status IN
        ('PENDING_REVIEW', 'REVISION_REQUESTED', 'ON_HOLD', 'PUBLISHED', 'PAUSED', 'HIDDEN'))
);

CREATE INDEX idx_space_location ON space USING GIST (location);
CREATE INDEX idx_space_status_region ON space (status, region);
CREATE INDEX idx_space_provider ON space (provider_id);

CREATE TABLE space_facility
(
    space_id BIGINT      NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    facility VARCHAR(30) NOT NULL,
    PRIMARY KEY (space_id, facility)
);

CREATE TABLE space_activity
(
    space_id      BIGINT      NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    activity_type VARCHAR(30) NOT NULL,
    PRIMARY KEY (space_id, activity_type)
);

-- 공간 제공자가 대여 가능하다고 표시한 날짜 (캘린더)
CREATE TABLE space_available_date
(
    space_id       BIGINT NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    available_date DATE   NOT NULL,
    PRIMARY KEY (space_id, available_date)
);

CREATE INDEX idx_space_available_date_date ON space_available_date (available_date);

COMMENT ON TABLE space IS '빈 상가 공간';
COMMENT ON COLUMN space.region IS '좌표로 서버가 판정한 서비스 지역';
COMMENT ON COLUMN space.location IS 'WGS84 좌표 (x=경도, y=위도)';
COMMENT ON COLUMN space.building_use IS '건축물대장 기준 용도';
COMMENT ON COLUMN space.daily_price IS '1일 이용료(원)';
COMMENT ON COLUMN space.status IS 'PENDING_REVIEW 검수 대기 / REVISION_REQUESTED 수정 요청 / ON_HOLD 공개 보류 / PUBLISHED 공개 / PAUSED 일시 중단 / HIDDEN 관리자 숨김';
COMMENT ON COLUMN space.review_comment IS '가장 최근 검수 사유 (이력은 space_review)';
