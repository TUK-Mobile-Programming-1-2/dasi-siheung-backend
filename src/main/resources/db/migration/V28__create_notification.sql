-- 회원 알림함. 가격 제안 · 수락 · 거절처럼 상대가 한 일을 남기고, 커밋 뒤 같은 내용을 푸시(data-only)로 보낸다.
-- 푸시를 받지 못해도(알림 끔 · 방해금지 · 기기 없음) 알림함에는 항상 남는다. 탈퇴하면 지운다.
CREATE TABLE notification
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id      BIGINT       NOT NULL REFERENCES member (id) ON DELETE CASCADE,
    type           VARCHAR(30)  NOT NULL,
    application_id BIGINT REFERENCES space_application (id) ON DELETE CASCADE,
    title          VARCHAR(50)  NOT NULL,
    body           VARCHAR(300) NOT NULL,
    read_at        TIMESTAMP,
    created_at     TIMESTAMP    NOT NULL,
    CONSTRAINT ck_notification_type
        CHECK (type IN ('PRICE_OFFER_RECEIVED', 'PRICE_OFFER_ACCEPTED', 'PRICE_OFFER_REJECTED'))
);

CREATE INDEX idx_notification_member ON notification (member_id, id DESC);
CREATE INDEX idx_notification_member_unread ON notification (member_id) WHERE read_at IS NULL;
CREATE INDEX idx_notification_application ON notification (application_id);

COMMENT ON TABLE notification IS '회원 알림함 (푸시 수신 여부와 상관없이 남음)';
COMMENT ON COLUMN notification.member_id IS '받는 회원';
COMMENT ON COLUMN notification.type IS 'PRICE_OFFER_RECEIVED 가격 제안 도착 | PRICE_OFFER_ACCEPTED 내 제안 수락됨 | PRICE_OFFER_REJECTED 내 제안 거절됨';
COMMENT ON COLUMN notification.application_id IS '눌렀을 때 열 신청';
COMMENT ON COLUMN notification.read_at IS '처음 읽은 시각 (안 읽었으면 NULL)';
