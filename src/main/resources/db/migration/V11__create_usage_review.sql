-- 이용 후기. 이용이 끝난 확정 예약 1건당 후기 1개. (관리자 검수 이력 space_review 와 다른 테이블)
CREATE TABLE usage_review
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT        NOT NULL REFERENCES space_application (id) ON DELETE CASCADE,
    space_id       BIGINT        NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    reviewer_id    BIGINT        NOT NULL REFERENCES member (id),
    rating         SMALLINT      NOT NULL,
    content        VARCHAR(1000) NOT NULL,
    reply          VARCHAR(500),
    replied_at     TIMESTAMP,
    created_at     TIMESTAMP     NOT NULL,
    updated_at     TIMESTAMP     NOT NULL,
    CONSTRAINT uk_usage_review_application UNIQUE (application_id),
    CONSTRAINT ck_usage_review_rating CHECK (rating BETWEEN 1 AND 5)
);

CREATE INDEX idx_usage_review_space ON usage_review (space_id, created_at DESC);
CREATE INDEX idx_usage_review_reviewer ON usage_review (reviewer_id, created_at DESC);

-- 공간 평점: 합계 · 개수는 후기 작성 · 수정 · 삭제 때 UPDATE 한 문장으로 바꾸고, 평균은 DB 가 계산한다.
ALTER TABLE space
    ADD COLUMN review_count   INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN rating_sum     INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN rating_average NUMERIC(3, 2) GENERATED ALWAYS AS (
        CASE WHEN review_count = 0 THEN NULL ELSE ROUND(rating_sum::NUMERIC / review_count, 2) END) STORED,
    ADD CONSTRAINT ck_space_review_count CHECK (review_count >= 0 AND rating_sum >= 0);

COMMENT ON TABLE usage_review IS '이용 후기 (확정 예약 1건당 1개)';
COMMENT ON COLUMN usage_review.reply IS '공간 제공자 답글';
COMMENT ON COLUMN space.rating_average IS '평균 평점 (후기 없으면 NULL) — 자동 계산';
