-- 1:1 문의. 회원(이용자 · 공간 제공자)이 남기고 관리자가 한 번 답변한다. 답변하면 문의한 회원에게 푸시를 보낸다.
CREATE TABLE inquiry
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   BIGINT        NOT NULL REFERENCES member (id),
    category    VARCHAR(20)   NOT NULL,
    content     VARCHAR(1000) NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    answer      VARCHAR(2000),
    answered_by BIGINT REFERENCES member (id),
    answered_at TIMESTAMP,
    created_at  TIMESTAMP     NOT NULL,
    updated_at  TIMESTAMP     NOT NULL,
    CONSTRAINT ck_inquiry_category CHECK (category IN ('APPLICATION', 'PAYMENT', 'ACCOUNT', 'SPACE', 'ETC')),
    CONSTRAINT ck_inquiry_status CHECK (status IN ('WAITING', 'ANSWERED')),
    -- 답변 대기면 답변이 없고, 답변 완료면 답변 · 답변 시각이 반드시 있다.
    CONSTRAINT ck_inquiry_answer CHECK (
        (status = 'WAITING' AND answer IS NULL AND answered_at IS NULL)
            OR (status = 'ANSWERED' AND answer IS NOT NULL AND answered_at IS NOT NULL))
);

CREATE INDEX idx_inquiry_member ON inquiry (member_id, created_at DESC, id DESC);
CREATE INDEX idx_inquiry_status ON inquiry (status, created_at);

COMMENT ON TABLE inquiry IS '1:1 문의 (회원이 작성, 관리자가 답변)';
COMMENT ON COLUMN inquiry.category IS 'APPLICATION: 신청 · 예약, PAYMENT: 결제 · 환불, ACCOUNT: 계정, SPACE: 공간 정보, ETC: 기타';
COMMENT ON COLUMN inquiry.status IS 'WAITING: 답변 대기, ANSWERED: 답변 완료';
COMMENT ON COLUMN inquiry.answered_by IS '답변한 관리자';

-- 문의 첨부 사진. 문의를 등록한 뒤 따로 올린다. 개인정보가 담길 수 있어 비공개 버킷에 두고 임시 주소로 보여준다.
CREATE TABLE inquiry_photo
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id    BIGINT       NOT NULL REFERENCES inquiry (id) ON DELETE CASCADE,
    storage_path  VARCHAR(300) NOT NULL,
    original_name VARCHAR(255),
    content_type  VARCHAR(100) NOT NULL,
    file_size     BIGINT       NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

CREATE INDEX idx_inquiry_photo_inquiry ON inquiry_photo (inquiry_id, id);

COMMENT ON TABLE inquiry_photo IS '1:1 문의 첨부 사진 (문의당 최대 3장, 문의한 회원 · 관리자만 임시 주소로 열람)';
