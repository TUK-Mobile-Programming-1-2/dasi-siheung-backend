-- 회원. 관리자(ADMIN)는 가입 API 로 만들 수 없고 DBA 가 role 을 직접 바꿔 승격한다. (docs/ADMIN_GUIDE.md)
CREATE TABLE member
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(254) NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    name            VARCHAR(30)  NOT NULL,
    phone           VARCHAR(20),
    role            VARCHAR(20)  NOT NULL,
    status          VARCHAR(20)  NOT NULL,
    suspended_until TIMESTAMP,
    withdrawn_at    TIMESTAMP,
    created_at      TIMESTAMP    NOT NULL,
    updated_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uk_member_email UNIQUE (email),
    CONSTRAINT ck_member_role CHECK (role IN ('USER', 'PROVIDER', 'ADMIN')),
    CONSTRAINT ck_member_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

COMMENT ON TABLE member IS '회원';
COMMENT ON COLUMN member.email IS '로그인 이메일 (소문자로 정규화해 저장)';
COMMENT ON COLUMN member.password_hash IS 'BCrypt 해시';
COMMENT ON COLUMN member.phone IS '휴대폰 번호 (숫자만)';
COMMENT ON COLUMN member.role IS 'USER: 이용자, PROVIDER: 공간 제공자, ADMIN: 관리자';
COMMENT ON COLUMN member.suspended_until IS '이용 정지 해제 시각 (NULL 이면 무기한)';
