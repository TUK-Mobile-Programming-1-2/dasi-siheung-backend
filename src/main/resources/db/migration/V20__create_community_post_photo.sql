-- 커뮤니티 게시글 사진. 공개 버킷에 두고 저장소 안의 경로만 저장한다. (주소는 조회할 때 만든다)
-- 올린 순서(id)대로 보여주고, 첫 사진이 목록 썸네일이다. 글이 지워지면 사진 행도 함께 지운다.
CREATE TABLE community_post_photo
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id      BIGINT       NOT NULL REFERENCES community_post (id) ON DELETE CASCADE,
    storage_path VARCHAR(300) NOT NULL,
    created_at   TIMESTAMP    NOT NULL
);

CREATE INDEX idx_community_post_photo_post ON community_post_photo (post_id, id);

COMMENT ON TABLE community_post_photo IS '커뮤니티 게시글 사진 (글당 최대 5장, 첫 사진이 목록 썸네일)';
