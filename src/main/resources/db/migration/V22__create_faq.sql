-- 자주 묻는 질문. 관리자 웹에서 추가 · 수정 · 삭제 · 순서 변경한다.
-- display_order 가 작을수록 위에 보이고, 같으면 먼저 만든 것(id)이 위다. 새 질문은 맨 뒤에 붙는다.
CREATE TABLE faq
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category      VARCHAR(20)   NOT NULL,
    question      VARCHAR(200)  NOT NULL,
    answer        VARCHAR(2000) NOT NULL,
    display_order INTEGER       NOT NULL,
    created_at    TIMESTAMP     NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    CONSTRAINT ck_faq_category CHECK (category IN ('ACCOUNT', 'APPLICATION', 'SPACE', 'COMMUNITY', 'ETC')),
    CONSTRAINT ck_faq_display_order CHECK (display_order >= 0)
);

CREATE INDEX idx_faq_display_order ON faq (display_order, id);

COMMENT ON TABLE faq IS '자주 묻는 질문 (관리자가 관리, 누구나 조회)';
COMMENT ON COLUMN faq.category IS 'ACCOUNT: 회원 · 계정, APPLICATION: 신청 · 예약, SPACE: 공간 등록 · 관리, COMMUNITY: 커뮤니티 · 신고, ETC: 기타';
COMMENT ON COLUMN faq.display_order IS '보여주는 순서 (0부터, 작을수록 위)';

