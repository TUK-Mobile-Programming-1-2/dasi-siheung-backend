-- 관리자 검수 이력. 공간의 최근 결과는 space.status / review_comment 에도 남는다.
CREATE TABLE space_review
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id              BIGINT        NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    admin_id              BIGINT        NOT NULL REFERENCES member (id),
    decision              VARCHAR(20)   NOT NULL,
    reason                VARCHAR(1000),
    authority_verified    BOOLEAN       NOT NULL,
    address_matched       BOOLEAN       NOT NULL,
    building_unit_matched BOOLEAN       NOT NULL,
    area_matched          BOOLEAN       NOT NULL,
    usage_matched         BOOLEAN       NOT NULL,
    created_at            TIMESTAMP     NOT NULL,
    CONSTRAINT ck_space_review_decision CHECK (decision IN ('APPROVE', 'REQUEST_REVISION', 'HOLD'))
);

CREATE INDEX idx_space_review_space ON space_review (space_id, created_at DESC);

COMMENT ON TABLE space_review IS '공간 검수 이력';
COMMENT ON COLUMN space_review.authority_verified IS '제공 권한: 증빙으로 공간을 제공할 권한 확인';
COMMENT ON COLUMN space_review.address_matched IS '주소: 등록 주소와 증빙 일치';
COMMENT ON COLUMN space_review.building_unit_matched IS '건물·호실: 등록 건물·호실과 증빙 일치';
COMMENT ON COLUMN space_review.area_matched IS '면적: 등록 면적과 증빙 일치';
COMMENT ON COLUMN space_review.usage_matched IS '용도: 등록 용도와 증빙 일치';
