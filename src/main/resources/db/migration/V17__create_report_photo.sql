-- 신고 증거 사진. 신고할 때 함께 올리고 관리자만 본다. (비공개 버킷, 신고당 최대 5장)
CREATE TABLE report_photo
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id     BIGINT       NOT NULL REFERENCES report (id) ON DELETE CASCADE,
    storage_path  VARCHAR(300) NOT NULL,
    original_name VARCHAR(255),
    content_type  VARCHAR(100) NOT NULL,
    file_size     BIGINT       NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

CREATE INDEX idx_report_photo_report ON report_photo (report_id, id);

COMMENT ON TABLE report_photo IS '신고 증거 사진 (관리자만 열람, 임시 주소로 제공)';
