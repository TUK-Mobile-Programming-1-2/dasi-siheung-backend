-- 커뮤니티 게시글 · 댓글. 신고 처리(숨김)를 위해 상태 컬럼을 둔다.
CREATE TABLE community_post
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id     BIGINT        NOT NULL REFERENCES member (id),
    category      VARCHAR(20)   NOT NULL,
    title         VARCHAR(100)  NOT NULL,
    content       VARCHAR(5000) NOT NULL,
    comment_count INTEGER       NOT NULL DEFAULT 0,
    view_count    INTEGER       NOT NULL DEFAULT 0,
    status        VARCHAR(20)   NOT NULL DEFAULT 'VISIBLE',
    version       BIGINT        NOT NULL DEFAULT 0,
    created_at    TIMESTAMP     NOT NULL,
    updated_at    TIMESTAMP     NOT NULL,
    CONSTRAINT ck_community_post_category
        CHECK (category IN ('NOTICE', 'LOCAL_NEWS', 'SPACE_STORY', 'RECRUIT', 'QUESTION')),
    CONSTRAINT ck_community_post_status CHECK (status IN ('VISIBLE', 'HIDDEN')),
    CONSTRAINT ck_community_post_counts CHECK (comment_count >= 0 AND view_count >= 0)
);

CREATE INDEX idx_community_post_list ON community_post (status, category, created_at DESC);
CREATE INDEX idx_community_post_author ON community_post (author_id);

CREATE TABLE community_comment
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT        NOT NULL REFERENCES community_post (id) ON DELETE CASCADE,
    author_id  BIGINT        NOT NULL REFERENCES member (id),
    content    VARCHAR(1000) NOT NULL,
    status     VARCHAR(20)   NOT NULL DEFAULT 'VISIBLE',
    created_at TIMESTAMP     NOT NULL,
    updated_at TIMESTAMP     NOT NULL,
    CONSTRAINT ck_community_comment_status CHECK (status IN ('VISIBLE', 'HIDDEN'))
);

CREATE INDEX idx_community_comment_post ON community_comment (post_id, id);

COMMENT ON TABLE community_post IS '커뮤니티 게시글 (공지는 관리자만)';
COMMENT ON COLUMN community_post.comment_count IS '보이는 댓글 수 — UPDATE 한 문장으로 더하고 뺀다';
COMMENT ON TABLE community_comment IS '커뮤니티 댓글';
