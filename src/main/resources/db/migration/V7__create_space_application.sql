-- 공간 이용 신청. 정가는 신청 시점 값으로 고정하고, 가격 협의 상태를 함께 둔다.
CREATE TABLE space_application
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id             BIGINT        NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    applicant_id         BIGINT        NOT NULL REFERENCES member (id),
    activity_type        VARCHAR(30)   NOT NULL,
    activity_title       VARCHAR(60)   NOT NULL,
    plan                 VARCHAR(2000) NOT NULL,
    headcount            INTEGER       NOT NULL,
    start_date           DATE          NOT NULL,
    end_date             DATE          NOT NULL,
    list_daily_price     INTEGER       NOT NULL,
    list_total_price     INTEGER       NOT NULL,
    total_price          INTEGER       NOT NULL,
    negotiation_status   VARCHAR(20)   NOT NULL,
    pending_offer_amount INTEGER,
    status               VARCHAR(20)   NOT NULL,
    status_reason        VARCHAR(500),
    decided_at           TIMESTAMP,
    version              BIGINT        NOT NULL DEFAULT 0,
    created_at           TIMESTAMP     NOT NULL,
    updated_at           TIMESTAMP     NOT NULL,
    CONSTRAINT ck_space_application_period CHECK (start_date <= end_date),
    CONSTRAINT ck_space_application_headcount CHECK (headcount BETWEEN 1 AND 200),
    CONSTRAINT ck_space_application_price CHECK (list_daily_price >= 0 AND list_total_price >= 0 AND total_price >= 0),
    CONSTRAINT ck_space_application_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'CLOSED')),
    CONSTRAINT ck_space_application_negotiation
        CHECK (negotiation_status IN ('NONE', 'WAITING_PROVIDER', 'WAITING_APPLICANT', 'AGREED')),
    CONSTRAINT ck_space_application_pending_offer
        CHECK ((negotiation_status IN ('WAITING_PROVIDER', 'WAITING_APPLICANT')) = (pending_offer_amount IS NOT NULL))
);

CREATE INDEX idx_space_application_applicant ON space_application (applicant_id, created_at DESC);
CREATE INDEX idx_space_application_space_period ON space_application (space_id, status, start_date, end_date);

COMMENT ON TABLE space_application IS '공간 이용 신청';
COMMENT ON COLUMN space_application.list_total_price IS '신청 시점 정가 합계 (1일 이용료 × 일수)';
COMMENT ON COLUMN space_application.total_price IS '현재 합의 금액 — 협의 전에는 정가 합계';
COMMENT ON COLUMN space_application.pending_offer_amount IS '상대 답변을 기다리는 가격 제안 금액';
COMMENT ON COLUMN space_application.status_reason IS '거절 · 취소 · 자동 마감 사유';
