-- 신고. 관리자가 처리(숨김 · 이용 정지 · 기각)하면 같은 대상의 대기 중 신고도 함께 처리된다.
CREATE TABLE report
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT        NOT NULL REFERENCES member (id),
    target_type VARCHAR(20)   NOT NULL,
    target_id   BIGINT        NOT NULL,
    reason      VARCHAR(30)   NOT NULL,
    detail      VARCHAR(1000),
    status      VARCHAR(20)   NOT NULL,
    action      VARCHAR(30),
    admin_id    BIGINT REFERENCES member (id),
    admin_note  VARCHAR(500),
    resolved_at TIMESTAMP,
    created_at  TIMESTAMP     NOT NULL,
    updated_at  TIMESTAMP     NOT NULL,
    CONSTRAINT ck_report_target_type CHECK (target_type IN ('SPACE', 'POST', 'COMMENT', 'MEMBER')),
    CONSTRAINT ck_report_reason
        CHECK (reason IN ('FRAUD', 'FALSE_INFORMATION', 'ABUSIVE', 'SPAM', 'INAPPROPRIATE', 'OTHER')),
    CONSTRAINT ck_report_status CHECK (status IN ('PENDING', 'RESOLVED', 'DISMISSED')),
    CONSTRAINT ck_report_action CHECK (action IS NULL OR action IN ('DISMISS', 'HIDE', 'SUSPEND', 'HIDE_AND_SUSPEND'))
);

-- 같은 회원이 같은 대상을 처리 전에 두 번 신고하지 못한다.
CREATE UNIQUE INDEX uk_report_pending_per_reporter ON report (reporter_id, target_type, target_id)
    WHERE status = 'PENDING';
CREATE INDEX idx_report_status ON report (status, created_at);
CREATE INDEX idx_report_target ON report (target_type, target_id);

COMMENT ON TABLE report IS '신고 (공간 · 게시글 · 댓글 · 회원)';
COMMENT ON COLUMN report.action IS '관리자 처리: DISMISS 기각 | HIDE 숨김 | SUSPEND 이용 정지 | HIDE_AND_SUSPEND 둘 다';
