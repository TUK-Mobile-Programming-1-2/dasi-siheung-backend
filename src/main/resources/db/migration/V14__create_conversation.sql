-- 1:1 소통. 이용자가 공간 제공자에게 공간별로 대화를 연다. 앱은 주기적으로 새 메시지를 조회(폴링)한다.
CREATE TABLE conversation
(
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id                      BIGINT       NOT NULL REFERENCES space (id) ON DELETE CASCADE,
    user_id                       BIGINT       NOT NULL REFERENCES member (id),
    provider_id                   BIGINT       NOT NULL REFERENCES member (id),
    last_message_at               TIMESTAMP,
    last_message_preview          VARCHAR(100),
    user_last_read_message_id     BIGINT       NOT NULL DEFAULT 0,
    provider_last_read_message_id BIGINT       NOT NULL DEFAULT 0,
    created_at                    TIMESTAMP    NOT NULL,
    updated_at                    TIMESTAMP    NOT NULL,
    CONSTRAINT uk_conversation_space_user UNIQUE (space_id, user_id)
);

CREATE INDEX idx_conversation_user ON conversation (user_id, last_message_at DESC);
CREATE INDEX idx_conversation_provider ON conversation (provider_id, last_message_at DESC);

CREATE TABLE message
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT        NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    sender_id       BIGINT        NOT NULL REFERENCES member (id),
    content         VARCHAR(1000) NOT NULL,
    created_at      TIMESTAMP     NOT NULL
);

CREATE INDEX idx_message_conversation ON message (conversation_id, id);

COMMENT ON TABLE conversation IS '1:1 대화 (공간별 이용자 ↔ 공간 제공자)';
COMMENT ON COLUMN conversation.user_last_read_message_id IS '이용자가 마지막으로 읽은 메시지 ID — 안 읽은 수 계산용';
COMMENT ON TABLE message IS '1:1 대화 메시지 (ID 오름차순 = 보낸 순)';
