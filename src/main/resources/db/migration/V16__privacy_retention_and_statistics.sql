-- 개인정보 파기 · 비식별화와 통계 보존.
-- 1) 이용이 끝난 확정 예약은 먼저 월별 통계에 더한 뒤(counted_in_stats), 보관 기간이 지나면 신청서 글을 비식별화한다.
-- 2) 오래된 1:1 대화 · 활동 사진은 지운다. 실행 기록은 privacy_purge_log 에 남긴다.
ALTER TABLE space_application
    ADD COLUMN counted_in_stats BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN anonymized_at    TIMESTAMP;

CREATE INDEX idx_space_application_stats ON space_application (status, end_date) WHERE NOT counted_in_stats;
CREATE INDEX idx_space_application_retention ON space_application (end_date) WHERE anonymized_at IS NULL;

CREATE TABLE monthly_usage_stat
(
    stat_month    DATE        NOT NULL,
    region        VARCHAR(20) NOT NULL,
    activity_type VARCHAR(30) NOT NULL,
    booking_count INTEGER     NOT NULL,
    booked_days   INTEGER     NOT NULL,
    total_amount  BIGINT      NOT NULL,
    PRIMARY KEY (stat_month, region, activity_type)
);

CREATE TABLE privacy_purge_log
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    executed_by             BIGINT REFERENCES member (id),
    application_cutoff      DATE      NOT NULL,
    counted_bookings        INTEGER   NOT NULL,
    anonymized_applications INTEGER   NOT NULL,
    deleted_conversations   INTEGER   NOT NULL,
    deleted_activity_photos INTEGER   NOT NULL,
    executed_at             TIMESTAMP NOT NULL
);

COMMENT ON COLUMN space_application.counted_in_stats IS '월별 통계(monthly_usage_stat)에 더했는지';
COMMENT ON COLUMN space_application.anonymized_at IS '활동 이름 · 계획 · 사유를 비식별화한 시각';
COMMENT ON TABLE monthly_usage_stat IS '월별 · 지역별 · 활동별 확정 이용 통계 (개인 식별 정보 없음)';
COMMENT ON TABLE privacy_purge_log IS '개인정보 파기 실행 기록 (executed_by 가 NULL 이면 자동 실행)';
